    const statusText = modal.querySelector('#ai-status-text');
    const diffContainer = modal.querySelector('#ai-diff-container');
    const diffScroll = modal.querySelector('#ai-diff-scroll');
    const diffCount = modal.querySelector('#ai-diff-count');
